/* «Сходу Всё» — пожизненный доступ, который не продаётся за деньги
 * внутри приложения, а достаётся за троих приведённых друзей.
 *
 * Почему так, а не подписка.
 *
 * Р7 конституции запрещает продавать учебное содержимое. Поэтому в
 * премиуме нет ни одного слова, ни одного правила и ни одного режима:
 * всё это открыто всем и всегда. Премиум состоит из внешнего вида,
 * спокойствия и мелких удобств — того, что можно отнять, не отняв
 * язык. Ровно поэтому его не стыдно раздавать бесплатно.
 *
 * Зачёркнутая цена — не приём давления. Это ответ на вопрос «а что я
 * вообще получаю»: без числа набор выглядит горстью мелочей, с числом
 * становится понятной вещью. Цена честная: столько же стоит год
 * похожих приложений, и мы действительно нигде не берём денег.
 *
 * Три друга, а не один: один — это случайность, трое — это уже
 * компания. И именно компания, а не запас алмазов, удерживает
 * человека в ритме.
 */

export const PRICE = { amount: 30, currency: '$', period: 'год' };
export const NEEDED = 3;

/* Каждая строка — то, что человек получает НАВСЕГДА. Ни одна не
   касается содержимого: только внешность, ритм и удобство. */
export const PERKS = [
  { icon: '🎭', title: 'Весь гардероб',   sub: 'Все аватары, шляпы и цвета открыты сразу' },
  { icon: '🧊', title: 'Ритм не рвётся',  sub: 'Заморозка возвращается каждую неделю сама' },
  { icon: '📈', title: 'Полная история',  sub: 'Полгода одним взглядом, а не только эта неделя' },
  { icon: '🎚', title: 'Занятие под себя', sub: 'Длина захода от 5 до 40 слов без ограничений' },
  { icon: '💠', title: 'Знак рядом с именем', sub: 'Видно, что ты привёл своих' },
];

export function friendsCount(state) {
  return ((state.referral || {}).friends || []).length;
}

export function isActive(state) {
  return Boolean((state.premium || {}).active) || friendsCount(state) >= NEEDED;
}

export function progress(state) {
  const have = Math.min(NEEDED, friendsCount(state));
  return { have, need: NEEDED, left: Math.max(0, NEEDED - have), done: have >= NEEDED };
}

/* Границы длины занятия расширяются: это одна из привилегий. */
export function sizeBounds(state) {
  return isActive(state) ? { min: 5, max: 40 } : { min: 8, max: 30 };
}

/* Строка под кнопкой. Меняется на каждом шаге, чтобы человек видел
   не «0 из 3», а свою позицию в коротком сюжете. */
export function statusLine(state) {
  const { have, left } = progress(state);
  if (left === 0) return { key: 'Всё открыто. Навсегда.', vars: {} };
  if (have === 0) return { key: 'Трое друзей — и всё это твоё навсегда.', vars: {} };
  if (left === 1) return { key: 'Остался один друг. Последний шаг.', vars: {} };
  return { key: 'Ещё {v0} друга — и всё открыто навсегда.', vars: { v0: left } };
}
